export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const lang = navigator.language?.slice(0, 2).toLowerCase();
  return (LOCALES as string[]).includes(lang) ? (lang as Locale) : "en";
}

type TranslateVars = Record<string, string | number>;

type I18n = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (k: MsgKey, vars?: TranslateVars) => string;
};

function fill(template: string, vars?: TranslateVars): string {
  if (!vars) return template;
  let out = template;
  for (const [key, val] of Object.entries(vars)) {
    out = out.replace(new RegExp(`\\{${key}\\}`, "g"), String(val));
  }
  return out;
}

const I18nContext = createContext<I18n>({
  locale: "en",
  setLocale: () => undefined,
  t: (k, vars) => fill(en[k], vars),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const saved = readStorage(LOCALE_STORAGE_KEY);
    if (saved && (LOCALES as string[]).includes(saved)) {
      setLocaleState(saved as Locale);
      return;
    }
    setLocaleState(detectLocale());
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = LOCALE_DIR[locale];
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    writeStorage(LOCALE_STORAGE_KEY, l);
  }, []);

  const t = useCallback(
    (k: MsgKey, vars?: TranslateVars) => fill(DICTS[locale][k] ?? en[k], vars),
    [locale],
  );
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  return useContext(I18nContext);
}
